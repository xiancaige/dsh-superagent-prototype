const reason = (error: unknown): string => error instanceof Error ? error.message : String(error)
// Accept POSIX roots, rooted Windows drives and UNC shares, but not drive-relative C:dir or root-relative \\dir.
const absolute = (description: string) => s.string().pattern(/^(?:\/|[A-Za-z]:[\\/]|\\\\[^\\/]+[\\/][^\\/]+(?:[\\/]|$))/).description(`${description} Absolute path.`)
/**
 * The TP environment a rollout configures in the profile patch (dsh-plugins/superagent-rollout.json,
 * generated by setup-superagent.mjs). Every field is optional: schemastery materialises a nested object
 * even when the profile omits it, so `recoveryEnabled` alone decides, and an absent section is read as
 * false and leaves the deployment exactly as a phase-B one (no environment, `held:false`, `noEnvironment`).
 * Present and true, the configured values replace the process environment, so the desired state lives in
 * the repository rather than in one machine's shell. setup-superagent.mjs refuses a section whose paths
 * are missing or whose port is illegal before it is ever written here.
 */
export const EnvironmentConfig = s.object({
  recoveryEnabled: s.boolean().default(false)
    .description('Enable the TP editor environment: the persistent exclusivity lease and the B2 editor recovery. False keeps the deployment without an environment.'),
  projectFile: s.string().required(false).description('Absolute TP .uproject the environment covers; no other UE project is ever touched.'),
  editorExe: s.string().required(false).description('Absolute UnrealEditor.exe the TP project opens with.'),
  mcpPort: s.natural().min(1).max(65535).default(55255).description('TPMcp port of the TP editor.'),
  captureTool: s.string().default('CaptureWidgetBlueprintScreenshot').description('MCP capture tool used as the readiness handshake and for visual evidence.'),
  captureToolset: s.string().default('TPEditor.TPEditorToolset').description('MCP toolset that owns the capture tool.'),
  waitSeconds: s.natural().min(1).required(false).description('How long a recovery waits for the TPMcp handshake, in seconds.'),
})
export type EnvironmentConfig = ReturnType<typeof EnvironmentConfig>
/** Plugin configuration of the dsh-superagent entry. Volatile fields apply without a restart because dsh-superagent reads them on each use; changing `stateDir` remounts the plugin. */
export const Config = s.object({
  executionMode: s.union(['github', 'local']).default('github').description('GitHub deployment, or same-process local execution without external accounts or agent Git/PATH changes.'),
  stateDir: absolute('Directory for the database, locks, worker shims, the agent\'s git configuration and, by default, the ticket directories.').required(),
  workspaceMode: s.union(['isolated', 'source']).default('isolated').description('Source uses sourceRoot directly, skips prepare, and shares the project checkout. Isolated preserves per-ticket directories.'),
  sourceRoot: absolute('Existing project root for explicit local source workspace mode.').required(false),
  environment: EnvironmentConfig.description('TP editor environment this deployment holds exclusively across a ticket; omitted by deployments without an editor.'),
  promptMaxChars: s.number().min(LIMITS.promptMaxChars.min).max(LIMITS.promptMaxChars.max).step(1).default(100000)
    .description('Largest saved prompt configuration, in characters.').volatile(),
  admissionContextMaxPages: s.number().min(LIMITS.admissionContextMaxPages.min).max(LIMITS.admissionContextMaxPages.max).step(1).default(10)
    .description('Pages of thread context one assessment may read.').volatile(),
  admissionContextTimeoutMs: s.number().min(LIMITS.admissionContextTimeoutMs.min).max(LIMITS.admissionContextTimeoutMs.max).step(1)
    .default(15000).description('Time limit of one context read during an assessment, in milliseconds.').volatile(),
})
export type DeploymentConfig = ReturnType<typeof Config>
export interface Machine {
  /** Omitted by older callers means github; only explicit local mode bypasses account/environment setup. */
  executionMode?: 'github' | 'local'
  workspaceMode?: 'isolated' | 'source'
  sourceRoot?: string
  stateDir: string
  /**
   * The rollout's TP environment, already validated by the schema; undefined leaves the deployment without
   * one. Present with `recoveryEnabled: false` means the repository switched the environment off, and the
   * process environment may not re-enable it.
   */
  environment?: EnvironmentConfig
  promptMaxChars: Volatile<number>
  admissionContextMaxPages: Volatile<number>
  admissionContextTimeoutMs: Volatile<number>
}
const MOVED: Record<string, string> = {
  repository: 'on the GitHub Source', branchPrefix: 'in the prepare command of the Execution settings', github: 'on the GitHub Source',
  feishu: 'on the Feishu Source', author: 'prompt text', repositoryPath: 'in the prepare command of the Execution settings',
  worktreeRoot: 'the ticket directory of the Execution settings', blockedCommands: 'in the Execution settings',
}

/** Read machine settings and reject unknown configuration keys (naming where deprecated keys moved). */
export function machineOf(config: DeploymentConfig): Machine {
  const unknown = Object.keys(config).filter(key => !(key in (Config.dict ?? {})))
  if (unknown.length) throw new Error(`dsh-superagent configuration has keys it does not use: ${unknown.map(key => MOVED[key] ? `${key} (now ${MOVED[key]})` : key).join(', ')}; docs/006-deployment.md lists the keys`)
  const { executionMode, stateDir, workspaceMode, sourceRoot, environment, promptMaxChars, admissionContextMaxPages, admissionContextTimeoutMs } = config
  if (workspaceMode === 'source') {
    if (executionMode !== 'local' || !sourceRoot) throw new Error('source workspace requires executionMode=local and sourceRoot')
    if (!statSync(sourceRoot).isDirectory()) throw new Error('sourceRoot must be an existing directory')
  } else if (sourceRoot) throw new Error('sourceRoot requires workspaceMode=source')
  return { executionMode, stateDir, workspaceMode, ...sourceRoot ? { sourceRoot } : {}, ...environment ? { environment } : {}, promptMaxChars, admissionContextMaxPages, admissionContextTimeoutMs }
}

export const GithubAccountsSchema = z.object({
  repository: z.string().trim().regex(/^([A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+)?$/, 'owner/name').default(''),
  cli: z.string().trim().default(''),
})
export const FeishuBotSchema = z.object({
  cli: z.string().trim().default(''),
  configDir: z.string().trim().regex(/^(?:\/|[A-Za-z]:[\\/]|\\\\[^\\/]+[\\/][^\\/]+(?:[\\/]|$))/, 'Absolute configuration directory').optional(),
})
/** Source configuration keys that affect deployment setup and trigger a restart when changed. */
export const SETUP_FIELDS: Readonly<Record<string, readonly string[]>> = { github: Object.keys(GithubAccountsSchema.shape), feishu: Object.keys(FeishuBotSchema.shape) }

export interface Deployment extends Machine {
  /** In explicit local mode repository and every github field are empty: no account/remote exists.
   * Keep the legacy shape for GitHub consumers; an optional Feishu bot is independent of GitHub. */
  repository: string
  github: { cli: string; login: string; noreply: string }
  feishu?: FeishuBot
}
export interface FeishuBot { cli: string; configDir?: string; appId: string; brand: 'feishu' | 'lark'; botId: string; name: string }

/** Resolve a command name or absolute path to an executable file, ignoring the worker shim directory. */
export function executable(name: string, path: string, exclude?: string): string {
  if (name.includes('/') && !isAbsolute(name)) throw new Error(`${name} must be a command name or an absolute path`)
  const candidates = isAbsolute(name) ? [name] : path.split(delimiter).filter(dir => isAbsolute(dir) && !(exclude && sameDirectory(dir, exclude))).map(dir => join(dir, name))
  for (const candidate of candidates) {
    try { if (statSync(candidate).isFile()) { accessSync(candidate, constants.X_OK); return candidate } }
    catch { /* Not an executable file here; try the next PATH directory. */ }
  }
  throw new Error(`${name} is not an executable file${isAbsolute(name) ? '' : ' on PATH'}`)
}

export type Probe = (argv: string[], env?: NodeJS.ProcessEnv) => Promise<string>
/** Run startup checks through DSH's worker subprocess service with worker shims removed from PATH so a `gh` wrapper script reaches the real binary. */
export function workerProbe(subprocess: SubprocessRuntime, stateDir: string, cwd: string, signal: AbortSignal): Probe {
  const path = withoutDirectory(process.env.PATH ?? '', workerBin(stateDir))
  return (argv, env) => runAsWorker(subprocess, argv, cwd, AbortSignal.any([signal, AbortSignal.timeout(60_000)]),
    feishuEnvironment(undefined, { PATH: path, ...env }))
}

const GithubUser = z.object({ login: z.string().regex(/^[A-Za-z0-9-]+$/), id: z.number().int().positive() })
const RepositoryAccess = z.object({ name: z.string().regex(/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/), push: z.boolean().nullable() })
function parsed<T>(schema: z.ZodType<T>, text: string): T | undefined {
  let value: unknown
  try { value = JSON.parse(text) } catch { return undefined /* Non-JSON output; the caller surfaces the setup failure. */ }
  const result = schema.safeParse(value)
  return result.success ? result.data : undefined
}
/** A local deployment has no remote or CLI identity, not a synthetic GitHub account. */
export function localDeployment(machine: Machine): Deployment {
  return { ...machine, executionMode: 'local', repository: '', github: { cli: '', login: '', noreply: '' } }
}
/** Verify the agent's GitHub CLI identity and push access, or resolve explicit local mode without probing. */
export async function resolveDeployment(machine: Machine, github: unknown, probe: Probe, path = process.env.PATH ?? ''): Promise<Deployment> {
  if (machine.executionMode === 'local') return localDeployment(machine)
  const { stateDir } = machine
  const accounts = GithubAccountsSchema.parse(github ?? {})
  const remote = accounts.repository
  if (!remote) throw new SetupError('repositoryUnset')
  if (!accounts.cli) throw new SetupError('agentCliUnset')
  let cli: string
  try { cli = executable(accounts.cli, path, workerBin(stateDir)) } catch (error) { throw new SetupError('agentCliMissing', { output: reason(error) }) }
  const text = await probe([cli, 'api', 'user']).catch((error: unknown) => { throw new SetupError('agentCliSignedOut', { output: reason(error) }) })
  const agent = parsed(GithubUser, text)
  if (!agent) throw new SetupError('agentCliNoAccount')
  // Use the canonical repository name returned by GitHub so renamed repositories match incoming notifications.
  const access = parsed(RepositoryAccess, await probe([cli, 'api', `repos/${remote}`, '--jq', '{name: .full_name, push: .permissions.push}']).catch((error: unknown) => {
    throw new SetupError('repositoryUnreadable', { account: agent.login, repository: remote, output: reason(error) })
  }))
  if (!access) throw new SetupError('repositoryUnreported', { repository: remote })
  const repository = access.name
  if (access.push !== true) throw new SetupError('repositoryReadOnly', { account: agent.login, repository })
  return { ...machine, repository, github: { cli, login: agent.login, noreply: `${agent.id}+${agent.login}@users.noreply.github.com` } }
}

const AuthStatus = z.object({ appId: z.string().regex(/^cli_[A-Za-z0-9]+$/), brand: z.enum(['feishu', 'lark']).default('feishu'), identities: z.object({ bot: z.object({ status: z.string() }) }) })
const BotInfo = z.object({ bot: z.object({ open_id: z.string().regex(/^ou_[A-Za-z0-9]+$/), app_name: z.string().default('') }) })
/**
 * Verify that the configured Feishu CLI is authenticated as a bot and restricted to strict mode `bot`.
 * Workers invoke this CLI as `lark-cli`, so a CLI that also permits a user identity would let workers act as that user.
 */
export async function resolveFeishuBot(machine: Machine, feishu: unknown, probe: Probe, path = process.env.PATH ?? ''): Promise<FeishuBot | undefined> {
  const { cli: name, configDir } = FeishuBotSchema.parse(feishu ?? {})
  if (!name) return undefined
  const fail = (error: unknown): never => { throw error instanceof SetupError ? error : new SetupError('feishuCliFailed', { output: reason(error) }) }
  let cli = ''
  try { cli = executable(name, path, workerBin(machine.stateDir)) } catch (error) { fail(error) }
  const run = (...args: string[]): Promise<string> => (configDir ? probe([cli, ...args], feishuEnvironment(configDir)) : probe([cli, ...args])).catch(fail)
  const text = await run('auth', 'status')
  const status = parsed(AuthStatus, text.slice(text.indexOf('{')))
  if (!status) return fail(new SetupError('feishuNoApp'))
  if (status.identities.bot.status !== 'ready') fail(new SetupError('feishuBotNotReady', { app: status.appId, status: status.identities.bot.status }))
  const mode = /strict-mode:\s*(\w+)/.exec(await run('config', 'strict-mode'))?.[1]
  if (mode !== 'bot') fail(new SetupError('feishuUserIdentity', { mode: mode ?? 'unknown' }))
  // `--format json` unwraps only `data`, whereas this endpoint returns the payload under `bot`.
  const info = parsed(BotInfo, (await run('api', 'GET', '/open-apis/bot/v3/info', '--as', 'bot', '--format', 'ndjson')).split('\n')[0] ?? '')
  if (!info) return fail(new SetupError('feishuNoBot'))
  return { cli, ...(configDir ? { configDir } : {}), appId: status.appId, brand: status.brand, botId: info.bot.open_id, name: info.bot.app_name }
}
